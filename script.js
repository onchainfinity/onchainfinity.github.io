function getShareLinks(data) {
  const destinations = {
    whatsapp: ['https://wa.me/', { text: `${data.text}\n${data.url}` }],
    facebook: ['https://www.facebook.com/sharer/sharer.php', { u: data.url }],
    linkedin: ['https://www.linkedin.com/sharing/share-offsite/', { url: data.url }],
    x: ['https://twitter.com/intent/tweet', { text: data.text, url: data.url }]
  };
  return Object.fromEntries(Object.entries(destinations).map(([name, [address, parameters]]) => {
    const url = new URL(address);
    url.search = new URLSearchParams(parameters).toString();
    return [name, url.href];
  }));
}

